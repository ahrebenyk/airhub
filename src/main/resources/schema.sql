CREATE TABLE IF NOT EXISTS users (
    id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login       VARCHAR(50) NOT NULL UNIQUE,
    password    VARCHAR(200) NOT NULL,
    role        VARCHAR(10) NOT NULL CHECK (role IN ('ADMIN', 'USER')),
    can_edit    BOOLEAN DEFAULT TRUE NOT NULL,
    can_reports BOOLEAN DEFAULT TRUE NOT NULL
);

CREATE TABLE IF NOT EXISTS settings (
    id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(50) NOT NULL UNIQUE,
    val         VARCHAR(200),
    description VARCHAR(200)
);

CREATE TABLE IF NOT EXISTS user_log (
    id      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ts      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    login   VARCHAR(50),
    action  VARCHAR(30),
    details VARCHAR(1000)
);

CREATE TABLE IF NOT EXISTS airlines (
    id      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name    VARCHAR(100) NOT NULL UNIQUE,
    country VARCHAR(50)
);

CREATE TABLE IF NOT EXISTS flights (
    id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    flight_no  VARCHAR(10) NOT NULL,
    airline_id INT NOT NULL REFERENCES airlines (id),
    type       VARCHAR(10) NOT NULL CHECK (type IN ('Виліт', 'Приліт')),
    city       VARCHAR(50) NOT NULL,
    sched_time TIMESTAMP NOT NULL,
    gate       VARCHAR(5),
    status     VARCHAR(20) NOT NULL CHECK (status IN ('За розкладом', 'Посадка', 'Затримано', 'Відбув', 'Прибув', 'Скасовано'))
);

-- Functions and the trigger are re-registered on every start so they always point to the current classes
-- Database functions are implemented as static methods of DbServer
DROP ALIAS IF EXISTS GET_SETTING;
DROP ALIAS IF EXISTS CLEAN_LOG;
CREATE ALIAS GET_SETTING FOR 'org.grebenyk.airhub.db.DbServer.getSetting';
CREATE ALIAS CLEAN_LOG FOR 'org.grebenyk.airhub.db.DbServer.cleanLog';

-- The trigger is implemented by DbServer.FlightTrigger ($ denotes a nested class)
DROP TRIGGER IF EXISTS flights_trg;
CREATE TRIGGER flights_trg BEFORE INSERT, UPDATE ON flights
    FOR EACH ROW CALL 'org.grebenyk.airhub.db.DbServer$FlightTrigger';

-- The trigger is implemented by DbServer.UserTrigger: password hashing and protection of the last administrator
DROP TRIGGER IF EXISTS users_trg;
CREATE TRIGGER users_trg BEFORE INSERT, UPDATE, DELETE ON users
    FOR EACH ROW CALL 'org.grebenyk.airhub.db.DbServer$UserTrigger';

-- Migration of databases created by earlier versions: longer column for hashes, plain passwords are hashed by users_trg
ALTER TABLE users ALTER COLUMN password SET DATA TYPE VARCHAR(200);
UPDATE users SET password = password WHERE password NOT LIKE 'pbkdf2$%';
